// Visual verification for UI jobs.
//
// Found in a real session: a UI change passed every test because the tests
// checked text, not appearance, and it looked nothing like the agreed
// design. A job with `visual` renders the named routes in the sandbox's
// headless Chromium (the repository's own Playwright, offline, through the
// same runner as verification) and keeps screenshots as job artifacts, in
// light and dark, desktop and phone. The General gets the paths, and a
// review scout (reviews: <job id>) gets the screenshots and the reference
// design with the instruction to list every visible difference.
//
// It needs @playwright/test in the repository (the browser-playwright
// harness) and a way to serve the app: the repository's playwright.config
// webServer, or `visual.server`. Components without a route render through
// whatever serves them (a Storybook iframe route works).

import fs from "node:fs";
import path from "node:path";

export const VISUAL_DIR = ".openclaw/nomarmy-visual";
export const SCREENSHOT_DIR = "test-results/nomarmy-visual";
export const SHOTS = Object.freeze([
  { scheme: "light", device: "desktop", viewport: { width: 1280, height: 800 }, mobile: false },
  { scheme: "dark", device: "desktop", viewport: { width: 1280, height: 800 }, mobile: false },
  { scheme: "light", device: "phone", viewport: { width: 390, height: 844 }, mobile: true },
  { scheme: "dark", device: "phone", viewport: { width: 390, height: 844 }, mobile: true },
]);
const CONFIG_NAMES = ["playwright.config.ts", "playwright.config.mts", "playwright.config.js", "playwright.config.mjs", "playwright.config.cjs"];

export function routeSlug(route) {
  const s = String(route).replace(/^https?:\/\/[^/]+/, "").replace(/[^A-Za-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return (s || "root").slice(0, 80);
}

/** Problems with a job's visual block, before anything runs. */
export function visualProblems(visual) {
  if (!visual) return [];
  const problems = [];
  if (!visual.routes?.length) problems.push("visual.routes needs at least one route to render, e.g. \"/settings\"");
  for (const r of visual.routes ?? []) if (!/^\/[^\s]*$/.test(r)) problems.push(`visual.routes: "${r}" must be a path starting with / (the base URL comes from the app's server)`);
  return problems;
}

/** The Playwright test that takes every screenshot. */
export function visualSpec({ routes }) {
  return `// Generated by nomArmy for visual verification. Not part of the repository.
import { test } from "@playwright/test";
const routes = ${JSON.stringify(routes)};
const shots = ${JSON.stringify(SHOTS)};
const slug = ${routeSlug.toString()};
for (const route of routes) {
  for (const s of shots) {
    test(\`\${route} \${s.scheme} \${s.device}\`, async ({ browser, baseURL }) => {
      const context = await browser.newContext({ baseURL, viewport: s.viewport, colorScheme: s.scheme, isMobile: s.mobile, hasTouch: s.mobile, deviceScaleFactor: s.mobile ? 2 : 1 });
      const page = await context.newPage();
      try {
        const response = await page.goto(route, { waitUntil: "networkidle", timeout: 30000 }).catch(() => page.goto(route, { waitUntil: "load" }));
        await page.waitForTimeout(400);
        await page.screenshot({ path: \`${SCREENSHOT_DIR}/\${slug(route)}--\${s.scheme}--\${s.device}.png\`, fullPage: true });
        // A screenshot of an error page isn't a picture of the UI.
        if (!response || response.status() >= 400) throw new Error(\`\${route} answered HTTP \${response ? response.status() : "nothing"}\`);
      } finally { await context.close(); }
    });
  }
}
`;
}

/** The config: the repository's own (for its webServer), Chromium only. */
export function visualConfig({ repoConfig = null, baseUrl = null, server = null }) {
  const imp = repoConfig ? `import base from "../../${repoConfig.replace(/\.(?:[cm]?[jt]s)$/, "")}";\n` : "const base = {};\n";
  return `// Generated by nomArmy for visual verification. Not part of the repository.
import { defineConfig } from "@playwright/test";
${imp}const root = process.cwd();
// Playwright runs a webServer in the config's folder unless told otherwise.
const own = ${JSON.stringify(server ? { command: server, url: baseUrl, reuseExistingServer: false, timeout: 120000 } : null)};
const servers = own ? [{ ...own, cwd: root }] : [].concat(base.webServer ?? []).map((w) => ({ ...w, cwd: !w.cwd ? root : w.cwd.startsWith("/") ? w.cwd : root + "/" + (w.cwd.startsWith("./") ? w.cwd.slice(2) : w.cwd) }));
export default defineConfig({
  testDir: ".",
  testMatch: "visual.spec.mjs",
  outputDir: root + "/test-results/nomarmy-visual-output",
  reporter: "line",
  retries: 0,
  workers: 1,
  timeout: 90000,
  use: { ...(base.use ?? {}), baseURL: ${JSON.stringify(baseUrl)} ?? base.use?.baseURL ?? servers[0]?.url },
  projects: [{ name: "chromium", use: { browserName: "chromium" } }],
  ...(servers.length ? { webServer: servers } : {}),
});
`;
}

/**
 * Write the spec and config into the worktree (under .openclaw/, which the
 * Git record ignores) and return the command to run.
 */
export function prepareVisual({ worktree, visual }) {
  const repoConfig = CONFIG_NAMES.find((name) => fs.existsSync(path.join(worktree, name))) ?? null;
  if (!repoConfig && !visual.server) return { problem: "no playwright.config in the repository root and no visual.server command, so nothing serves the app to screenshot" };
  if (!repoConfig && !visual.base_url) return { problem: "visual.server needs visual.base_url, the URL it serves" };
  const dir = path.join(worktree, VISUAL_DIR);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "visual.spec.mjs"), visualSpec({ routes: visual.routes }));
  const configFile = repoConfig && /\.ts$/.test(repoConfig) ? "visual.config.ts" : "visual.config.mjs";
  const config = visualConfig({ repoConfig, baseUrl: visual.base_url ?? null, server: visual.server ?? null });
  fs.writeFileSync(path.join(dir, configFile), config);
  return { command: `npx --no-install playwright test --config ${VISUAL_DIR}/${configFile}`, repoConfig };
}

export function cleanupVisual(worktree) {
  try { fs.rmSync(path.join(worktree, VISUAL_DIR), { recursive: true, force: true }); } catch { /* best effort */ }
}

/** Screenshot artifacts from a verification result, absolute paths. */
export function screenshotsFrom(result, artifactRoot) {
  return (result?.artifacts ?? []).filter((a) => a.includes(`${SCREENSHOT_DIR}/`) && a.endsWith(".png")).map((a) => path.join(artifactRoot, a));
}

/** Expected screenshot names, to report any the run didn't produce. */
export function expectedShots(routes) {
  return routes.flatMap((r) => SHOTS.map((s) => `${routeSlug(r)}--${s.scheme}--${s.device}.png`));
}

/** The review issue line for the General. */
export function visualIssue({ shots, expected, reference, status, reason }) {
  if (!shots.length) return `VISUAL CHECK DIDN'T RUN: ${reason ?? `the screenshot run was ${status}`}. The UI's appearance is unchecked.`;
  const missing = expected.filter((name) => !shots.some((s) => s.endsWith(`/${name}`)));
  const failed = status === "fail" ? ` The screenshot run FAILED (a route answered with an error, or didn't load): read ${path.join(path.dirname(path.dirname(path.dirname(path.dirname(shots[0])))), "visual.log")} first; these may show error pages.` : "";
  return `VISUAL REVIEW: ${shots.length} screenshot(s) (light and dark, desktop and phone) in ${path.dirname(shots[0])}${missing.length ? `; ${missing.length} didn't render (${missing.slice(0, 4).join(", ")}${missing.length > 4 ? ", ..." : ""})` : ""}. ${reference ? `Compare them with the approved design (${reference}) and` : "No reference design was given;"} list every visible difference before accepting, or run a review scout with reviews: <this job>, which gets the screenshots${reference ? " and the reference" : ""}.${failed}`;
}

/** What a review scout is told when the reviewed job has screenshots. */
export function visualReviewBrief({ files, reference }) {
  return `\n\nVISUAL REVIEW: the reviewed job's screenshots are in ${files.join(", ")}${reference ? `, and the approved design is ${reference}` : ""}. Open each image and list every visible difference from ${reference ? "the approved design" : "what the task asks for"}: layout, spacing, color in light and dark, text, missing or extra elements, and anything broken at phone width. One finding per difference, citing the screenshot file.`;
}
