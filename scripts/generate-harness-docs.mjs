import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { HARNESS_ROOT, loadHarnesses } from "../lib/harnesses.mjs";

export const HARNESS_DOCS = fileURLToPath(new URL("../docs/harnesses.md", import.meta.url));
const cell = (value) => String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll("|", "&#124;").replaceAll("\n", " ").replaceAll("\r", " ");

export function generateHarnessDocs(root = HARNESS_ROOT) {
  const { harnesses, problems } = loadHarnesses(root);
  if (problems.length) throw new Error(problems.map(({ name, reason }) => `${name}: ${reason}`).join("\n"));
  const rows = Object.values(harnesses).sort((a, b) => a.name.localeCompare(b.name)).map((spec) => {
    const detects = spec.detect.map((rule) => Object.entries(rule).map(([kind, value]) => `${kind}: ${value}`).join(", ")).join("; ") || "none";
    const requires = Object.entries(spec.requires).map(([key, value]) => `${key}: ${value}`).join(", ") || "none";
    return `| [${spec.name}](https://github.com/rayson-tech/nomarmy/blob/main/harnesses/${spec.name}/README.md) | ${cell(spec.summary)} | ${cell(detects)} | ${spec.network} | ${cell(requires)} |`;
  });
  return `<!-- Generated by npm run docs:harnesses. Do not edit by hand. -->
# Harnesses

A harness is a data-only folder describing detection, image layers, and proposed verification profiles. Matched harnesses compose one cached image for workers and verification: toolchains first, then Python, Node, and declarative layers, respecting \`after\`. Tags hash the recipe and copied dependency files. Verification profiles remain proposals; network and service extensions are not enabled by this registry.

- **none**: offline verification (default).
- **services**: fake services on a private network with no route out (planned).
- **allowlist**: verification-only access to operator-approved hosts, with dedicated test tenants and throwaway credentials, never production (planned).

Workers always remain offline. See the [plan](plans/2026-09-25-sandbox-dependencies.md) and [Adding a harness](../CONTRIBUTING.md#adding-a-harness).

| Harness | Summary | Detects | Network | Requires |
|---------|---------|---------|---------|----------|
${rows.join("\n")}
`;
}

export function checkHarnessDocs(root = HARNESS_ROOT, output = HARNESS_DOCS) {
  if (fs.readFileSync(output, "utf8") !== generateHarnessDocs(root)) {
    throw new Error("Harness docs are stale. Run npm run docs:harnesses.");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(HARNESS_DOCS, generateHarnessDocs());
}
